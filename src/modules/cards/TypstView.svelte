<script lang="ts">
	// Rendered Typst markup (flashcards). Black-on-transparent SVG, inverted in dark mode.
	import { typstError, typstSvg } from '#lib/typst.ts';
	import { cn } from '#lib/utils.ts';

	let { src, class: className }: { src: string; class?: string } = $props();
	let svg = $state('');
	let err = $state('');

	$effect(() => {
		const s = src;
		let alive = true;
		if (!s.trim()) {
			svg = err = '';
			return;
		}
		typstSvg(s).then(
			(r) => alive && ((svg = r), (err = '')),
			(e) => alive && (err = typstError(e))
		);
		return () => (alive = false);
	});
</script>

<div class={cn('dark:invert [&_svg]:h-auto [&_svg]:w-full', className)}>
	{#if err}
		<p class="font-mono text-xs text-muted-foreground">{err}</p>
	{:else}
		<!-- SVG generated by the Typst compiler from the user's own card text -->
		<!-- eslint-disable-next-line svelte/no-at-html-tags -->
		{@html svg}
	{/if}
</div>
